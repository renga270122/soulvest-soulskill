def get_examples_for_role(job_title):
    """Get relevant examples for a job title"""
    # Try exact match first
    if job_title in PROFESSIONAL_SUMMARIES:
        return {
            'summaries': PROFESSIONAL_SUMMARIES[job_title],
            'bullets': WORK_EXPERIENCE_EXAMPLES.get(job_title, []),
            'projects': PROJECT_EXAMPLES.get(job_title, [])
        }
    
    # Try partial match
    for key in PROFESSIONAL_SUMMARIES.keys():
        if key.lower() in job_title.lower() or job_title.lower() in key.lower():
            return {
                'summaries': PROFESSIONAL_SUMMARIES[key],
                'bullets': WORK_EXPERIENCE_EXAMPLES.get(key, []),
                'projects': PROJECT_EXAMPLES.get(key, [])
            }
    
    # Default return
    return {
        'summaries': [],
        'bullets': [],
        'projects': []
    }

def get_all_job_roles():
    """Get list of all available job roles"""
    return list(PROFESSIONAL_SUMMARIES.keys())
