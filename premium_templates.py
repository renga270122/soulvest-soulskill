def get_template_by_category(category: str):
    """Get all templates for a specific category"""
    return {k: v for k, v in PREMIUM_TEMPLATES.items() if v["category"] == category}


def get_template_recommendations(industry: str, experience_level: str):
    """Get recommended templates based on industry and experience"""
    recommendations = []
    
    # Map industries to template categories
    industry_mapping = {
        "Technology": ["Technology", "Professional"],
        "Healthcare": ["Healthcare", "Professional"],
        "Finance": ["Finance", "Professional", "Business"],
        "Education": ["Education", "Professional"],
        "Engineering": ["Engineering", "Professional"],
        "Marketing": ["Marketing", "Creative"],
        "Sales": ["Sales", "Business"],
        "Legal": ["Legal", "Professional"],
        "Design": ["Creative"],
        "Business": ["Business", "Professional"]
    }
    
    # Map experience level
    if experience_level == "fresher" or experience_level == "entry":
        categories = ["Entry Level", "Professional"]
    else:
        categories = industry_mapping.get(industry, ["Professional"])
    
    # Get matching templates
    for template_id, template in PREMIUM_TEMPLATES.items():
        if template["category"] in categories:
            recommendations.append({
                "id": template_id,
                "name": template["name"],
                "description": template["description"],
                "ats_score": template["ats_score"],
                "best_for": template["best_for"]
            })
    
    # Sort by ATS score
    recommendations.sort(key=lambda x: x["ats_score"], reverse=True)
    
    return recommendations[:5]  # Return top 5 recommendations


def get_all_categories():
    """Get list of all template categories"""
    categories = set()
    for template in PREMIUM_TEMPLATES.values():
        categories.add(template["category"])
    return sorted(list(categories))
